"""The project `lakana init --template medallion` writes: a small retail star schema.

Four generated bronze tables (stores, customers, products, sales), four cleaned silver tables,
a gold star (two dimensions, a customer dimension that keeps its history, one fact) and a wide
table, with layer rules, German translations and a glossary. The files are literal text, kept
equal to `docs/examples/medallion/project` (a test compares them). Nothing is downloaded: the rows
are computed by the first query, so every machine and every run gets the same tables.
"""

from __future__ import annotations

_LAKANA_YAML = """\
# Lakana project. Reference: https://lakana-labs.github.io/lakana/how-to/projects/
repo: {repo}
# The language of the descriptions in the asset headers; translations/de.yaml translates the
# gold tables into German.
main_language: en
defaults:
  materialize: table
requirements:
  fields: [description]
# Layer rules: how data may flow. Bronze reads only sources, silver reads bronze, gold reads
# silver and gold. These are the medallion default; see
# https://lakana-labs.github.io/lakana/how-to/keep-layers-apart/
layers:
  bronze:
    reads: []
    write: [append, merge]
    kinds: none
  silver:
    reads: [bronze, silver]
    write: [replace, append, merge, view]
    kinds: [staging]
  gold:
    reads: [silver, gold]
    write: [replace, append, merge, history, view]
    kinds: [fact, dimension, wide]
# Table health runs at its defaults: every signal warns and none stops a run. To stop a run
# whose row count falls outside the usual band, see the commented line in
# assets/gold/fact_sales.sql and https://lakana-labs.github.io/lakana/reference/table-health/
"""

_README = """\
# {repo}

A Lakana project with a small retail star schema. Every table is generated by SQL, so it needs no
source system and builds the same everywhere.

| Layer | What it holds |
|---|---|
| `assets/bronze/` | The data as the shop systems deliver it: text for numbers and dates, stray spaces, a sale exported twice and an old customer row. Replace these files with your own sources. |
| `assets/silver/` | Cleaned: the right types, trimmed text, one row per key, and one check each (`checks/`). Silver tables are `kind: staging`. |
| `assets/gold/` | The star: `dim_store`, `dim_product`, `dim_customer` (keeps every version of a customer), the fact `fact_sales`, and `sales_wide` for spreadsheet users. |

`lakana.yaml` holds the layer rules, `translations/de.yaml` the German texts of the gold tables and
`glossary/sales.yaml` the two business terms that link to them.

Build it:

```
git init && git add -A && git commit -m 'Initial project'
lakana repo add {repo} --kind local --url "$PWD"
lakana deploy --env dev
lakana run --env dev
lakana sql "SELECT store, SUM(net_amount) AS net_amount FROM gold.sales_wide GROUP BY store ORDER BY store"
```

Each choice is explained in https://lakana-labs.github.io/lakana/how-to/model-a-star-schema/
"""  # ruff: ignore[line-too-long]

