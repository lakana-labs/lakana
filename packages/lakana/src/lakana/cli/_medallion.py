def medallion_files(repo: str) -> dict[str, str]:
    """Return the template's files for a repository.

    Parameters
    ----------
    repo
        The repository name, written into `lakana.yaml` and `README.md`.

    Returns
    -------
    dict of str to str
        Relative path to the text to write.
    """
    return {
        relative: text.format(repo=repo) if relative in MEDALLION_FORMATTED else text
        for relative, text in MEDALLION_TEMPLATE.items()
    }
