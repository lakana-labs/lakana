def _is_dev_build(version: str) -> bool:
    """Report whether `version` is a development or local build no index will have.

    Parameters
    ----------
    version
        The CLI's version string.

    Returns
    -------
    bool
        `True` for ``.dev`` releases and local versions (``+...``, ``0+unknown``).
    """
    return ".dev" in version or "+" in version


def _git_lacks_identity(directory: Path) -> bool:
    """Report whether `git commit` in `directory` would fail for want of a name or email.

    Asks git itself (`git var`), so config files, environment variables and its own
    guessing are all taken into account exactly as a commit would.

    Parameters
    ----------
    directory
        Where the project was written.

    Returns
    -------
    bool
        `True` only when git ran and could not resolve an author or committer identity;
        `False` when it has one, and when git is missing or cannot be run.
    """
    for variable in ("GIT_AUTHOR_IDENT", "GIT_COMMITTER_IDENT"):
        try:
            result = subprocess.run(  # nosec B603 B607 -- fixed argv
                ["git", "var", variable],
                cwd=directory,
                capture_output=True,
                check=False,
                timeout=3,
            )
        except (OSError, subprocess.SubprocessError):
            return False
        if result.returncode != 0:
            return True
    return False


def write_project(
    directory: Path,
    repo: str,
    *,
    sample: bool = True,
    ci_auth: str = "oidc",
    template: str | None = None,
) -> list[Path]:
    """Write every template into `directory`, refusing to overwrite anything.

    Parameters
    ----------
    directory
        The project directory; created if missing.
    repo
        The repository name for `lakana.yaml` and `pyproject.toml`.
    sample
        Whether to write the sample assets and check as well.
    ci_auth
        ``oidc``: the CI files exchange the job's ID token; ``pat``: they read a stored token.
    template
        A `Template` value: its asset and README, a pyproject with ``lakana[assets]`` and a
        test that parses Python assets; `None` for none.

    Returns
    -------
    list of Path
        The files written.

    Raises
    ------
    CliError
        Exit 2 if any target exists or a parent is
        not a directory (nothing is written); exit 3 on a filesystem error
        (files already written are removed).
    """
    templates = TEMPLATES | (PAT_CI_TEMPLATES if ci_auth == "pat" else {})
    texts = {
        relative: text.format(repo=repo, version=__version__)
        for relative, text in templates.items()
    }
    if sample:
        texts.update(SAMPLE)
    if template is not None:
        texts["pyproject.toml"] = _PYPROJECT_ASSETS.format(repo=repo, version=__version__)
        texts["tests/test_example.py"] = _TEST_PYTHON
        for relative, text in INGEST_TEMPLATES[template].items():
            texts[relative] = text.format(repo=repo) if relative == "README.md" else text
    targets = {directory / relative: text for relative, text in texts.items()}
    existing = [str(path) for path in targets if os.path.lexists(path)]
    if existing:
        raise CliError(f"Refusing to overwrite: {', '.join(existing)}")
    parents = {directory} | {
        directory / parent for relative in texts for parent in Path(relative).parents if parent.name
    }
    for parent in sorted(parents):
        if os.path.lexists(parent) and not parent.is_dir():
            raise CliError(
                f"Can't write the project into {directory}: {parent} is not a directory", 3
            )
    written: list[Path] = []
    try:
        for path, text in targets.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            with path.open("x") as handle:
                handle.write(text)
            written.append(path)
    except OSError as exc:
        for path in written:
            path.unlink(missing_ok=True)
        raise CliError(f"Can't write the project into {directory}: {exc}", 3) from exc
    return written


def _create_command(readme: str) -> str:
    """Find the `lakana connection create` line of a template's README.

    Parameters
    ----------
    readme
        The README's text.

    Returns
    -------
    str
        The command, as the README shows it.
    """
    return next(line.strip() for line in readme.splitlines() if "lakana connection create" in line)


